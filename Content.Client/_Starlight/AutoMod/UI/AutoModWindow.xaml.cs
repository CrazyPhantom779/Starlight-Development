    private void UpdateRuleListText()
    {
        if (_state == null || _state.Rules.Count == 0)
        {
            RuleListLabel.Text = "No runtime rules yet. Click Create New Disabled Rule.";
            return;
        }

        RuleListLabel.Text = string.Join('\n', _state.Rules
            .OrderByDescending(x => x.Priority)
            .ThenBy(x => x.Id)
            .Select(x =>
                $"{(x.Enabled ? "ON " : "OFF")}  {x.Id}\n" +
                $"    {x.Name} | {x.Category} | {x.Severity} | {x.MatchKind}\n" +
                $"    {x.ActionSummary}"));
    }

    private static string FormatDashboard(AutoModUiState? state)
    {
        if (state == null)
            return "No AutoMod state yet.";

        var highSeverity = state.RecentIncidents.Count(x => x.Severity >= AutoModSeverity.High);
        return
            $"Recent incidents: {state.RecentIncidents.Count}\n" +
            $"High severity incidents: {highSeverity}\n" +
            $"Saved rules: {state.Rules.Count}\n" +
            $"Pending approvals: {state.PendingApprovals}\n" +
            $"Discord: {(state.DiscordEnabled ? "Enabled" : "Disabled")}\n" +
            $"Rule store: {state.RuleStorePath}\n\n" +
            "Rules are fully runtime-configurable. No YAML or PRs are needed for rule changes.";
    }

    private static string FormatIncidents(AutoModUiState? state)
    {
        if (state == null || state.RecentIncidents.Count == 0)
            return "No incidents.";

        return string.Join('\n', state.RecentIncidents.Take(100).Select(x =>
            $"{x.CreatedAtUtc:u} | {Age(x.CreatedAtUtc)} ago | {x.PlayerNameAtTime} | {x.Channel} | {x.RuleId} | {x.ActionTaken} | {x.Status}"));
    }

    private void LoadRuleById(string id)
    {
        if (_state == null)
            return;

        var rule = _state.EditableRules.FirstOrDefault(x => string.Equals(x.ID, id, StringComparison.OrdinalIgnoreCase));
        if (rule == null)
        {
            MainTitle.Text = "Rule not found";
            InfoPanel.Visible = true;
            MainText.Text = $"No AutoMod rule with ID '{id}' was found. Copy the ID exactly from the rule list.";
            return;
        }

        LoadRuleIntoEditor(rule);
    }

    private void LoadRuleIntoEditor(AutoModEditableRule rule)
    {
        _workingRule = rule;
        _levelIndex = 0;

        RuleId.Text = rule.ID;
        SelectedRuleId.Text = rule.ID;
        RuleName.Text = rule.Name;
        RuleDescription.Text = rule.Description ?? string.Empty;
        RuleCategory.Text = rule.Category;
        RulePriority.Text = rule.Priority.ToString(CultureInfo.InvariantCulture);
        RuleChannels.Text = string.Join(", ", rule.Channels);

        _enabled = rule.Enabled;
        _severity = rule.Severity;
        _matchKind = rule.Match.Kind;
        _normalization = rule.Match.Normalization;
        _requireBoundary = rule.Match.RequireWordBoundary;
        PatternEdit.Text = rule.Match.Pattern ?? string.Empty;
        SpamWindowSeconds.Text = Math.Max(1, (int) rule.Match.Window.TotalSeconds).ToString(CultureInfo.InvariantCulture);
        SpamMaxMessages.Text = rule.Match.MaxMessages.ToString(CultureInfo.InvariantCulture);
        SetText(WordsEdit, string.Join('\n', rule.Match.Words));
        SetText(AllowListEdit, string.Join('\n', rule.Match.AllowList));

        _scope = rule.Escalation.Scope;
        ScopeKey.Text = rule.Escalation.ScopeKey ?? string.Empty;
        PointsPerIncident.Text = rule.Escalation.PointsPerIncident.ToString(CultureInfo.InvariantCulture);
        DecayDays.Text = Math.Max(0, (int) rule.Escalation.Decay.TotalDays).ToString(CultureInfo.InvariantCulture);

        _evidenceMode = rule.Evidence.Mode;
        EvidencePreview.Text = rule.Evidence.MaxPreviewLength.ToString(CultureInfo.InvariantCulture);
        _showMatchedToken = rule.Evidence.ShowMatchedTokenToAdmins;

        _discordMode = rule.Discord.LogMode;
        _discordMinimum = rule.Discord.MinimumAction;

        if (_workingRule.Levels.Count == 0)
            _workingRule.Levels.Add(CreateDefaultLevel(1));

        LoadLevelIntoEditor(0);
        RefreshToggleButtons();
        ShowTab("Rules", _state);
    }

    private void LoadLevelIntoEditor(int index)
    {
        if (_workingRule == null)
            return;

        if (_workingRule.Levels.Count == 0)
            _workingRule.Levels.Add(CreateDefaultLevel(1));

        _levelIndex = Math.Clamp(index, 0, _workingRule.Levels.Count - 1);
        var level = _workingRule.Levels[_levelIndex];
        var primary = level.Actions.FirstOrDefault(x => x.Type != AutoModActionType.CreateNote)
            ?? level.Actions.FirstOrDefault()
            ?? new AutoModEditableAction { Type = AutoModActionType.Warn, Message = "Your message was blocked by AutoMod." };
        var note = level.Actions.FirstOrDefault(x => x.Type == AutoModActionType.CreateNote);

        LevelNumber.Text = (_levelIndex + 1).ToString(CultureInfo.InvariantCulture);
        LevelMinPoints.Text = level.MinPoints.ToString(CultureInfo.InvariantCulture);
        _cancelSpeech = level.CancelSpeech;
        _notifyAdmins = level.NotifyAdmins;
        _actionMode = level.ActionMode;
        _allowSpeechWhilePending = level.Approval.AllowSpeechWhilePending;
        ApprovalTimeoutMinutes.Text = Math.Max(1, (int) level.Approval.Timeout.TotalMinutes).ToString(CultureInfo.InvariantCulture);

        _actionType = primary.Type;
        WarnMessage.Text = primary.Message ?? string.Empty;
        KickBanReason.Text = primary.Reason ?? string.Empty;
        DurationMinutes.Text = Math.Max(0, (int) primary.Duration.TotalMinutes).ToString(CultureInfo.InvariantCulture);

        _createNote = note != null || primary.Type == AutoModActionType.CreateNote;
        var noteSource = note ?? primary;
        _actionSeverity = noteSource.Severity;
        NoteExpiryDays.Text = Math.Max(0, (int) noteSource.Expiry.TotalDays).ToString(CultureInfo.InvariantCulture);
        _appealable = noteSource.Appealable;

        RefreshToggleButtons();
    }

    private void SaveLoadedRule()
    {
        EnsureWorkingRule();
        SaveCurrentRuleToWorkingRule();
        SaveCurrentLevelToWorkingRule();
        SaveRuleRequested?.Invoke(_workingRule!, RuleEditReason.Text ?? "Saved from AutoMod UI");
    }

    private void DeleteLoadedRule()
    {
        var id = SelectedRuleId.Text ?? RuleId.Text ?? string.Empty;
        if (string.IsNullOrWhiteSpace(id))
            return;

        DeleteRuleRequested?.Invoke(id.Trim(), RuleEditReason.Text ?? "Deleted from AutoMod UI");
    }

    private void ToggleLoadedRule(bool enabled)
    {
        var id = SelectedRuleId.Text ?? RuleId.Text ?? string.Empty;
        if (string.IsNullOrWhiteSpace(id))
            return;

        ToggleRuleRequested?.Invoke(id.Trim(), enabled, RuleEditReason.Text ?? (enabled ? "Enabled from AutoMod UI" : "Disabled from AutoMod UI"));
    }

    private void EnsureWorkingRule()
    {
        if (_workingRule != null)
            return;

        var channels = new List<string>();
        channels.Add("OOC");
        channels.Add("LOOC");

        var levels = new List<AutoModEditableLevel>();
        levels.Add(CreateDefaultLevel(1));

        _workingRule = new AutoModEditableRule
        {
            ID = string.IsNullOrWhiteSpace(RuleId.Text) ? $"automod-rule-{DateTime.UtcNow:yyyyMMddHHmmss}" : RuleId.Text.Trim(),
            Name = string.IsNullOrWhiteSpace(RuleName.Text) ? "New AutoMod Rule" : RuleName.Text.Trim(),
            Enabled = false,
            Priority = 100,
            Category = "General",
            Severity = AutoModSeverity.Low,
            Channels = channels,
            Levels = levels,
            Source = "RuntimeUI",
        };
    }

    private void SaveCurrentRuleToWorkingRule()
    {
        if (_workingRule == null)
            return;

        _workingRule.ID = (RuleId.Text ?? string.Empty).Trim();
        _workingRule.Name = string.IsNullOrWhiteSpace(RuleName.Text) ? _workingRule.ID : RuleName.Text.Trim();
        _workingRule.Description = RuleDescription.Text?.Trim() ?? string.Empty;
        _workingRule.Enabled = _enabled;
        _workingRule.Priority = ParseInt(RulePriority.Text, 100);
        _workingRule.Category = string.IsNullOrWhiteSpace(RuleCategory.Text) ? "General" : RuleCategory.Text.Trim();
        _workingRule.Severity = _severity;
        _workingRule.Channels = SplitList(RuleChannels.Text).DefaultIfEmpty("OOC").ToList();
        _workingRule.Source = "RuntimeUI";

        _workingRule.AdminPolicy.AdminedUsers = AutoModAdminedPolicy.Ignore;
        _workingRule.AdminPolicy.DeadminnedUsers = AutoModAdminedPolicy.Moderate;
        _workingRule.AdminPolicy.IgnoreAdminChannels = true;

        _workingRule.Match.Kind = _matchKind;
        _workingRule.Match.WordSet = null;
        _workingRule.Match.Pattern = string.IsNullOrWhiteSpace(PatternEdit.Text) ? null : PatternEdit.Text;
        _workingRule.Match.Words = SplitList(GetText(WordsEdit)).ToList();
        _workingRule.Match.AllowList = SplitList(GetText(AllowListEdit)).ToList();
        _workingRule.Match.Normalization = _normalization;
        _workingRule.Match.RequireWordBoundary = _requireBoundary;
        _workingRule.Match.Window = TimeSpan.FromSeconds(Math.Max(1, ParseInt(SpamWindowSeconds.Text, 10)));
        _workingRule.Match.MaxMessages = Math.Max(1, ParseInt(SpamMaxMessages.Text, 5));
        _workingRule.Match.SimilarityThreshold = 0.85f;

        _workingRule.Evidence.Mode = _evidenceMode;
        _workingRule.Evidence.MaxPreviewLength = Math.Clamp(ParseInt(EvidencePreview.Text, 160), 8, 1000);
        _workingRule.Evidence.ShowMatchedTokenToAdmins = _showMatchedToken;

        _workingRule.Escalation.Scope = _scope;
        _workingRule.Escalation.ScopeKey = string.IsNullOrWhiteSpace(ScopeKey.Text) ? null : ScopeKey.Text.Trim();
        _workingRule.Escalation.PointsPerIncident = Math.Max(0, ParseInt(PointsPerIncident.Text, 1));
        _workingRule.Escalation.Decay = TimeSpan.FromDays(Math.Max(0, ParseInt(DecayDays.Text, 30)));
        _workingRule.Escalation.IncludeFalsePositives = false;
        _workingRule.Escalation.IncludeDecayed = false;

        var pingRolesOn = new List<AutoModActionType>();
        pingRolesOn.Add(AutoModActionType.Ban);

        _workingRule.Discord.LogMode = _discordMode;
        _workingRule.Discord.MinimumAction = _discordMinimum;
        _workingRule.Discord.PingRolesOn = pingRolesOn;
    }

    private void SaveCurrentLevelToWorkingRule()
    {
        if (_workingRule == null)
            return;

        if (_workingRule.Levels.Count == 0)
            _workingRule.Levels.Add(CreateDefaultLevel(1));

        _levelIndex = Math.Clamp(_levelIndex, 0, _workingRule.Levels.Count - 1);
        _workingRule.Levels[_levelIndex] = BuildLevelFromFields();
        _workingRule.Levels = _workingRule.Levels.OrderBy(x => x.MinPoints).ToList();
    }

    private AutoModEditableLevel BuildLevelFromFields()
    {
        var action = new AutoModEditableAction
        {
            Type = _actionType,
            Message = string.IsNullOrWhiteSpace(WarnMessage.Text) ? null : WarnMessage.Text,
            Reason = string.IsNullOrWhiteSpace(KickBanReason.Text) ? null : KickBanReason.Text,
            Duration = TimeSpan.FromMinutes(Math.Max(0, ParseInt(DurationMinutes.Text, 0))),
            Severity = _actionSeverity,
            Expiry = TimeSpan.FromDays(Math.Max(0, ParseInt(NoteExpiryDays.Text, 30))),
            Appealable = _appealable,
        };

        var actions = new List<AutoModEditableAction>();
        if (_actionType != AutoModActionType.LogOnly)
            actions.Add(action);

        if (_createNote && _actionType != AutoModActionType.CreateNote)
        {
            actions.Add(new AutoModEditableAction
            {
                Type = AutoModActionType.CreateNote,
                Severity = _actionSeverity,
                Expiry = TimeSpan.FromDays(Math.Max(0, ParseInt(NoteExpiryDays.Text, 30))),
                Appealable = _appealable,
            });
        }

        if (actions.Count == 0)
            actions.Add(new AutoModEditableAction { Type = AutoModActionType.LogOnly });

        return new AutoModEditableLevel
        {
            MinPoints = Math.Max(1, ParseInt(LevelMinPoints.Text, 1)),
            CancelSpeech = _cancelSpeech,
            NotifyAdmins = _notifyAdmins,
            ActionMode = _actionMode,
            Approval = new AutoModEditableApproval
            {
                Timeout = TimeSpan.FromMinutes(Math.Max(1, ParseInt(ApprovalTimeoutMinutes.Text, 3))),
                RequiredPermission = _actionType == AutoModActionType.Ban ? "AutoModAuthorizeBan" : "AutoModAuthorizeAction",
                AllowSpeechWhilePending = _allowSpeechWhilePending,
            },
            Actions = actions,
        };
    }

    private static AutoModEditableLevel CreateDefaultLevel(int number)
    {
        var actions = new List<AutoModEditableAction>();

        actions.Add(new AutoModEditableAction
        {
            Type = AutoModActionType.Warn,
            Message = "Your message was blocked by AutoMod.",
            Severity = AutoModSeverity.Low,
            Expiry = TimeSpan.FromDays(30),
            Appealable = true,
        });

        actions.Add(new AutoModEditableAction
        {
            Type = AutoModActionType.CreateNote,
            Severity = AutoModSeverity.Low,
            Expiry = TimeSpan.FromDays(30),
            Appealable = true,
        });

        return new AutoModEditableLevel
        {
            MinPoints = Math.Max(1, number),
            CancelSpeech = true,
            NotifyAdmins = true,
            ActionMode = AutoModActionMode.Immediate,
            Approval = new AutoModEditableApproval
            {
                Timeout = TimeSpan.FromMinutes(3),
                RequiredPermission = "AutoModAuthorizeAction",
                AllowSpeechWhilePending = false,
            },
            Actions = actions,
        };
    }

