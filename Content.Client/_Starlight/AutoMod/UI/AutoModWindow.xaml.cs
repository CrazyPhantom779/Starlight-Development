    public void Populate(AutoModUiState state)
    {
        _state = state;
        StatusLabel.Text =
            $"Ruleset: {state.RulesetVersion} | Enabled: {state.Enabled} | Shadow: {state.ShadowMode} | " +
            $"NullLink: {(state.NullLinkEnabled ? state.NullLinkHealthy ? "Synced" : "Degraded" : "Disabled")} | " +
            $"Outbox: {state.UnsyncedIncidents}";

        UpdateRuleListText();

        if (_workingRule == null && state.EditableRules.Count > 0)
            LoadRuleIntoEditor(state.EditableRules[0]);

        ShowDashboard(state);
    }

    public void ShowTab(string tab, AutoModUiState? state)
    {
        _state = state ?? _state;
        MainTitle.Text = tab;
        InfoPanel.Visible = tab != "Rules" && tab != "Tester";
        TesterControls.Visible = tab == "Tester";
        RuleEditorControls.Visible = tab == "Rules";

        MainText.Text = tab switch
        {
            "Dashboard" => FormatDashboard(_state),
            "Incident Log" => FormatIncidents(_state),
            "Approval Queue" => "Approval requests will appear here when rules use Mode: RequireApproval. Use that mode for bans or low-confidence regex rules.",
            "Player Lookup" => "Player-specific AutoMod review belongs here. Until the player panel hook is expanded, use Incident Log to search recent events.",
            "Discord Logs" => _state == null ? "No state." : $"Discord enabled: {_state.DiscordEnabled}\nDiscord logging is async and should never block chat.",
            "Sync / Health" => _state == null ? "No state." : $"NullLink enabled: {_state.NullLinkEnabled}\nNullLink healthy: {_state.NullLinkHealthy}\nUnsynced incidents: {_state.UnsyncedIncidents}\nRule store: {_state.RuleStorePath}",
            "Settings" => "Global AutoMod settings are CVar-backed. Rule behaviour is edited in the Rules tab and saved in-game.",
            _ => string.Empty,
        };

        if (tab == "Rules")
        {
            UpdateRuleListText();
            if (_workingRule == null && _state?.EditableRules.Count > 0)
                LoadRuleIntoEditor(_state.EditableRules[0]);
        }
    }

