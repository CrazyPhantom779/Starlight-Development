    private static string YesNo(bool value) => value ? "Yes" : "No";

    private static T NextEnum<T>(T current) where T : struct, Enum
    {
        var values = Enum.GetValues<T>();
        var index = Array.IndexOf(values, current);
        return values[(index + 1) % values.Length];
    }

    private static int ParseInt(string? value, int fallback)
    {
        return int.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsed)
            ? parsed
            : fallback;
    }

    private static IEnumerable<string> SplitList(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            yield break;

        foreach (var part in value.Split(new[] { '\n', '\r', ',' }, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            if (!string.IsNullOrWhiteSpace(part))
                yield return part.Trim();
        }
    }

    private static string Age(DateTime utc)
    {
        var span = DateTime.UtcNow - utc;
        if (span.TotalDays >= 1)
            return $"{(int) span.TotalDays}d";
        if (span.TotalHours >= 1)
            return $"{(int) span.TotalHours}h";
        if (span.TotalMinutes >= 1)
            return $"{(int) span.TotalMinutes}m";
        return $"{Math.Max(0, (int) span.TotalSeconds)}s";
    }

    private static string GetText(TextEdit edit)
    {
        return edit.TextLength == 0
            ? string.Empty
            : Rope.CollapseSubstring(edit.TextRope, 0..edit.TextLength);
    }

    private static void SetText(TextEdit edit, string text)
    {
        edit.TextRope = Rope.Leaf.Empty;
        edit.CursorPosition = default;
        edit.SelectionStart = default;

        if (!string.IsNullOrEmpty(text))
            edit.InsertAtCursor(text);
    }
