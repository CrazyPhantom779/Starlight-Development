def y(v, ind):
    pad = '  ' * ind
    if isinstance(v, dict):
        out = []
        for k, val in v.items():
            if isinstance(val, dict): out.append(f'{pad}{k}:'); out.append(y(val, ind + 1))
            else: out.append(f'{pad}{k}: {sc(val)}')
        return '\n'.join(out)
def sc(v):
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, list): return '[ ' + ', '.join(str(x) for x in v) + ' ]'
    return str(v)
