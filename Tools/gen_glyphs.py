def validate(name, chain):
    forms = [c for c in chain if meta[c][0] == 'Form']
    assert len(forms) == 1 and meta[chain[0]][0] == 'Form', f'{name}: needs exactly one Form first'
    deliv = meta[forms[0]][1]['deliv']; effs = [c for c in chain if meta[c][0] == 'Effect']
    assert 1 <= len(effs) <= 4, f'{name}: effect count'
    for e in effs:
        kind = meta[e][1]['kind']
        ok = kind == 'u' or (kind == 'w' and deliv == 'Aimed') or (kind == 'i' and deliv in ('Self', 'Burst'))
        assert ok, f'{name}: {e} incompatible with {deliv}'
    for a in [c for c in chain if meta[c][0] == 'Augment']:
        if meta[a][1]['kind'] == 'Split': assert deliv == 'Bolt', f'{name}: split needs bolt'
    assert len(chain) <= 8, f'{name}: too long'
