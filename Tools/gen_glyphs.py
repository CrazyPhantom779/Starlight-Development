def adj(a, b):
    ra, ca = divmod(a, 3); rb, cb = divmod(b, 3)
    return a != b and max(abs(ra - rb), abs(ca - cb)) == 1
def paths(n):
    out = []
    def rec(p):
        if len(p) == n: out.append(tuple(p)); return
        for nx in range(9):
            if nx not in p and adj(p[-1], nx): rec(p + [nx])
    for s in range(9): rec([s])
    return out
pool = {}
for n in (4, 5):
    for p in paths(n):
        key = min(p, p[::-1]); pool[key] = True
pool = sorted(pool.keys())
all_ids = [g[0] for g in FORMS] + [g[0] for g in EFFECTS] + [g[0] for g in AUGMENTS]
sigils = {}; used = set()
for gid in sorted(all_ids):
    h = int(hashlib.md5(gid.encode()).hexdigest(), 16)
    i = h % len(pool)
    while pool[i] in used: i = (i + 1) % len(pool)
    used.add(pool[i]); sigils[gid] = pool[i]

